def build(locale,count=10000,seed=20261010):
 rng=random.Random(seed)
 tasks,clocks,repeats=catalog(locale)
 rows={s:[] for s in ('train','dev','test')}
 today=dt.date(2026,10,10)
 def emit(split,family,parts,proposal=None,other=False):
  text='';spans=[]
  for token,label in parts:
   if not token:continue
   start=len(text);text+=token
   if label:spans.append(dict(start=start,end=len(text),label=label))
  if locale=='en' and split=='train' and rng.random()<.2:
   text=text.upper()
   if proposal:proposal=dict(proposal,title=proposal['title'].upper(),note=proposal['note'].upper())
  row=dict(id=f'{locale}-{split}-{len(rows[split])+1:05}',locale=locale,group=f'{locale}-{split}-{family}',text=text,preferredKind='TASK',now='2026-10-10T04:00:00Z',timezone='Asia/Shanghai' if locale=='zh' else 'UTC',provenance=PROVENANCE,annotationStatus='synthetic',split=split,spans=spans,expected=dict(decision='accept',proposal=proposal) if proposal else dict(decision='defer'))
  if other:row['trainingIntent']='OTHER'
  rows[split].append(row)
 def task(split,title,time,days,clock,i):
  due=(today+dt.timedelta(days=days)).isoformat()+'T'+clock
  p=dict(BASE,title=title,dueAt=due)
  if split=='dev':
   parts=[(title,'TITLE'),('，' if locale=='zh' else ', ',None),(time,'TIME')]
  elif i%4==0:parts=[(time,'TIME'),(('，' if locale=='zh' else ', ') if i%8==0 else (' ' if locale=='en' else ''),None),(title,'TITLE')]
  elif i%4==1:parts=[(title,'TITLE'),(' ' if locale=='en' else '',None),(time,'TIME')]
  elif i%4==2:parts=[('提醒我' if locale=='zh' else 'remind me to ',None),(title,'TITLE'),(' ' if locale=='en' else '',None),(time,'TIME')]
  else:parts=[('帮我' if locale=='zh' else 'please ',None),(time,'TIME'),(' ' if locale=='en' else '',None),(title,'TITLE')]
  emit(split,'task-time-comma' if split=='dev' else f'task-layout-{i%4}',parts,p)
 def habit(split,title,repeat,period,target,mask,time,clock,i):
  if time in ('转钟','24:00','at 24:00'):mask=((mask<<1)&127)|(mask>>6)
  p=dict(BASE,kind='HABIT',title=title,period=period,targetCount=target,weekdaysMask=mask,reminderTime=clock)
  if split=='dev':parts=[(title,'TITLE'),('，' if locale=='zh' else ', ',None),(repeat,'REPEAT'),(' ' if locale=='en' else '',None),(time,'TIME')]
  elif i%3==0:parts=[(repeat,'REPEAT'),(' ' if locale=='en' else '',None),(time,'TIME'),(('，' if locale=='zh' else ', ') if i%6==0 else (' ' if locale=='en' else ''),None),(title,'TITLE')]
  elif i%3==1:parts=[(title,'TITLE'),(' ' if locale=='en' else '',None),(repeat,'REPEAT'),(' ' if locale=='en' else '',None),(time,'TIME')]
  else:parts=[('记得' if locale=='zh' else 'remember to ',None),(repeat,'REPEAT'),(' ' if locale=='en' else '',None),(title,'TITLE'),(' ' if locale=='en' else '',None),(time,'TIME')]
  emit(split,'habit-time-comma' if split=='dev' else f'habit-layout-{i%3}',parts,p)
 for split,n in [('train',count),('dev',900)]:
  for i in range(n):
   title=rng.choice(TITLE_POOL[locale])
   if i%5 in (0,1):
    time,days,clock=rng.choice(tasks);task(split,title,time,days,clock,i)
   elif i%5 in (2,3):
    repeat,period,target,mask=rng.choice(repeats);time,clock=rng.choice(clocks)
    habit(split,title,repeat,period,target,mask,time,clock,i)
   else:
    time,_,_=rng.choice(tasks)
    if split=='train':
     token=rng.choice([f'不要{time}{title}',f'取消{time}的提醒{title}',f'我已经{title}了不用再提醒']) if locale=='zh' else rng.choice([f"don't remind me to {title} {time}",f'cancel the reminder to {title} {time}',f'I already did {title}, no reminder please',f'stop the {time} reminder for {title}',f'I no longer need reminders to {title} {time}'])
    else:token=f'并不需要你在{time}提醒我{title}' if locale=='zh' else f'please stop reminding me to {title} {time}'
    emit(split,'negative-train' if split=='train' else 'negative-stop-development',[(token,None)],other=True)
 # Standalone commands with no temporal slots; titles independent of TASK/HABIT elsewhere.
 for title in TITLE_POOL[locale]:emit('train','plain-command',[(title,'TITLE')],dict(BASE,title=title))
 # Explicit weekday dates; semantic offsets calculated directly from author-specified weekday.
 for weekday_index in range(7):
  weekday=['一','二','三','四','五','六','日'][weekday_index] if locale=='zh' else ['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'][weekday_index]
  for title in TITLE_POOL[locale][:12]:
   token=f'下周{weekday}上午九点' if locale=='zh' else f'next {weekday} at 9am'
   task('train',title,token,weekday_index-today.weekday()+7,'09:00',0)
 validate(rows)
 return rows


def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--output',type=Path,default=Path('data'))
 parser.add_argument('--count',type=int,default=10000)
 parser.add_argument('--replace-dev',action='store_true',help='Explicitly regenerate developer set; never allowed for blind test')
 args=parser.parse_args()
 for locale in ('zh','en'):
  rows=build(locale,args.count)
  root=args.output/locale;root.mkdir(parents=True,exist_ok=True)
  if (root/'dev.jsonl').exists() and not args.replace_dev:rows['dev']=load(root/'dev.jsonl')
  validate(rows)
  for split,examples in rows.items():(root/(split+'.jsonl')).write_text(''.join(json.dumps(r,ensure_ascii=False)+'\n' for r in examples))
  stats=dict(generationVersion=3,locale=locale,counts={k:len(v) for k,v in rows.items()},uniqueTexts={k:len({r['text'] for r in v}) for k,v in rows.items()},seed=20261010,provenance=PROVENANCE,independentlyReviewed=False)
  (root/'corpus-report.json').write_text(json.dumps(stats,ensure_ascii=False,indent=2))
  (root/'expression-catalog.json').write_text(json.dumps(dict(tasks=catalog(locale)[0],clocks=catalog(locale)[1],repeats=catalog(locale)[2]),ensure_ascii=False,indent=2))
  print(json.dumps(stats))

if __name__=='__main__':main()
